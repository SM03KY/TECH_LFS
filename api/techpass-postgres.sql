CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('admin', 'treasurer', 'auditor')),
    must_change_password SMALLINT NOT NULL DEFAULT 0 CHECK (must_change_password IN (0, 1)),
    is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS organization_settings (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    name VARCHAR(160) NOT NULL DEFAULT 'Organization Ledger',
    fiscal_year_start VARCHAR(80) NOT NULL DEFAULT 'January 1',
    currency CHAR(3) NOT NULL DEFAULT 'PHP',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transactions (
    id UUID PRIMARY KEY,
    entry_date DATE NOT NULL,
    category VARCHAR(20) NOT NULL,
    sub_category VARCHAR(100) NOT NULL,
    description VARCHAR(255) NOT NULL,
    manual_details TEXT NULL,
    raw_ocr_text TEXT NULL,
    corrected_ocr_text TEXT NULL,
    line_items_json JSONB NULL,
    receipt_image BYTEA NULL,
    receipt_image_type VARCHAR(32) NULL,
    amount DECIMAL(14, 2) NOT NULL,
    payment_method VARCHAR(80) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users (id),
    updated_by BIGINT NOT NULL REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_transactions_entry_date ON transactions (entry_date);
CREATE INDEX IF NOT EXISTS idx_transactions_category ON transactions (category);

ALTER TABLE transactions ADD COLUMN IF NOT EXISTS corrected_ocr_text TEXT NULL;
ALTER TABLE transactions ADD COLUMN IF NOT EXISTS line_items_json JSONB NULL;
